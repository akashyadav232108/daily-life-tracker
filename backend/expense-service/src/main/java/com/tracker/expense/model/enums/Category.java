package com.tracker.expense.model.enums;

/**
 * Pre-defined expense/income categories.
 * SALARY and FREELANCE are typically used with INCOME type.
 * All others are typically EXPENSE. The service does not enforce this.
 */
public enum Category {
    FOOD,
    TRANSPORT,
    RENT,
    UTILITIES,
    ENTERTAINMENT,
    SHOPPING,
    HEALTH,
    EDUCATION,
    SUBSCRIPTIONS,
    SALARY,
    FREELANCE,
    INVESTMENT,
    OTHER
}
